// ---- State ----
let airports = [];
let results = null; // loaded from results.json (generated by scripts/search_flights.py)
let selected = { origin: null, destination: null };

// ---- Load data ----
Promise.all([
  fetch("airports.json").then(r => r.json()),
  fetch("results.json").then(r => r.json()).catch(() => ({ routes: [] })) // ok if not generated yet
]).then(([airportData, resultsData]) => {
  airports = airportData;
  results = resultsData;
});

// ---- Autocomplete ----
function setupAutocomplete(inputId, suggestionsId, key) {
  const input = document.getElementById(inputId);
  const box = document.getElementById(suggestionsId);
  let activeIndex = -1;

  input.addEventListener("input", () => {
    selected[key] = null; // clear selection until they pick from the list
    const q = input.value.trim().toLowerCase();
    if (q.length < 1) { box.classList.remove("open"); box.innerHTML = ""; return; }

    const matches = airports.filter(a =>
      a.code.toLowerCase().startsWith(q) ||
      a.city.toLowerCase().includes(q) ||
      a.name.toLowerCase().includes(q)
    ).slice(0, 8);

    if (matches.length === 0) { box.classList.remove("open"); box.innerHTML = ""; return; }

    box.innerHTML = matches.map((a, i) =>
      `<div class="suggestion-item" data-index="${i}" data-code="${a.code}">
         <span class="code">${a.code}</span>${a.city}, ${a.country}
         <div class="meta">${a.name}</div>
       </div>`
    ).join("");
    box.classList.add("open");
    activeIndex = -1;

    box.querySelectorAll(".suggestion-item").forEach(el => {
      el.addEventListener("click", () => {
        const airport = airports.find(a => a.code === el.dataset.code);
        input.value = `${airport.city} (${airport.code})`;
        selected[key] = airport.code;
        box.classList.remove("open");
      });
    });
  });

  input.addEventListener("keydown", (e) => {
    const items = box.querySelectorAll(".suggestion-item");
    if (!items.length) return;
    if (e.key === "ArrowDown") { activeIndex = Math.min(activeIndex + 1, items.length - 1); }
    else if (e.key === "ArrowUp") { activeIndex = Math.max(activeIndex - 1, 0); }
    else if (e.key === "Enter") { if (activeIndex >= 0) items[activeIndex].click(); return; }
    else return;
    items.forEach(el => el.classList.remove("active"));
    items[activeIndex].classList.add("active");
  });

  document.addEventListener("click", (e) => {
    if (!input.contains(e.target) && !box.contains(e.target)) box.classList.remove("open");
  });
}

setupAutocomplete("origin", "originSuggestions", "origin");
setupAutocomplete("destination", "destinationSuggestions", "destination");

// ---- Search ----
document.getElementById("searchBtn").addEventListener("click", () => {
  const status = document.getElementById("status");
  const tripLength = parseInt(document.getElementById("tripLength").value, 10);

  if (!selected.origin || !selected.destination) {
    status.textContent = "Pick both airports from the dropdown list.";
    return;
  }
  if (!results) {
    status.textContent = "Results data hasn't loaded yet — try again in a moment.";
    return;
  }

  const match = results.routes.find(r =>
    r.origin === selected.origin &&
    r.destination === selected.destination &&
    r.trip_length === tripLength
  );

  const resultsCard = document.getElementById("resultsCard");
  const resultsList = document.getElementById("resultsList");
  const resultsMeta = document.getElementById("resultsMeta");

  if (!match) {
    status.textContent = "No data for this route/trip length yet. Add it to scripts/search_flights.py's ROUTES list and re-run the workflow.";
    resultsCard.style.display = "none";
    return;
  }

  status.textContent = "";
  resultsMeta.textContent = `${selected.origin} → ${selected.destination} · ${tripLength} days · updated ${match.updated_at}`;
  resultsList.innerHTML = match.windows.slice(0, 10).map(w =>
    `<div class="result-item">
       <span class="dates">${w.depart} → ${w.return}</span>
       <span class="price">$${w.price}</span>
     </div>`
  ).join("");
  resultsCard.style.display = "block";
});
